const TIMELINE_NAME: Record<string, string> = {
  original: "Timeline Original",
  "new-timeline": "Timeline Baru (MK 2011–MK11)",
  "new-era": "New Era (MK1 2023)",
};

function version(
  charId: string,
  gameId: string,
  timelineId: string,
  opts: Partial<CharacterVersion> = {},
): CharacterVersion {
  return {
    id: `${charId}-${gameId}`,
    label: NAMES[gameId] ?? gameId,
    gameId,
    gameTitle: NAMES[gameId] ?? gameId,
    timelineId,
    timelineName: TIMELINE_NAME[timelineId] ?? timelineId,
    abilities: [],
    weapons: [],
    organizations: [],
    verificationStatus: "pending-review",
    // Placeholder record — tidak ada assetURL, sehingga UI memakai fallback netral
    image: {
      assetId: `asset-${charId}-${gameId}-portrait`,
      assetType: "character_portrait",
      entityId: charId,
      gameId,
      characterVersionId: `${charId}-${gameId}`,
      rightsStatus: "pending-review",
      alt: `Potret ${NAMES[charId]} pada ${NAMES[gameId]}`,
    },
    ...opts,
  };
}

